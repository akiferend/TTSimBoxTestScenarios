float NTCLookup::tempToKohm(float targetTempC) {
    if (targetTempC <= ntcTable[0].tempC) return ntcTable[0].kohm;
    if (targetTempC >= ntcTable[TABLE_SIZE - 1].tempC) return ntcTable[TABLE_SIZE - 1].kohm;

    // Tablo adım aralığı tam 1°C ve -25°C'den başladığı için O(1) sabit hızda doğrudan indeks hesabı yapabiliriz:
    float indexFloat = targetTempC - ntcTable[0].tempC; // örn: 25.5 - (-25) = 50.5
    size_t i = (size_t)indexFloat;

    float t0 = ntcTable[i].tempC;
    float t1 = ntcTable[i + 1].tempC;
    float r0 = ntcTable[i].kohm;
    float r1 = ntcTable[i + 1].kohm;

    return r0 + (r1 - r0) * ((targetTempC - t0) / (t1 - t0));
}
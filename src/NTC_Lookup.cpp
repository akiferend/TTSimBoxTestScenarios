const int NTCLookup::tableSize = sizeof(NTCLookup::table) / sizeof(NTCPoint);

float NTCLookup::temperatureToKohm(float celsius) {
    if (tableSize == 0) return 0.0f;

    if (celsius <= table[0].tempC) return table[0].kohm;
    if (celsius >= table[tableSize - 1].tempC) return table[tableSize - 1].kohm;

    for (int i = 0; i < tableSize - 1; i++) {
        float t0 = table[i].tempC;
        float t1 = table[i + 1].tempC;

        if (celsius >= t0 && celsius <= t1) {
            float r0 = table[i].kohm;
            float r1 = table[i + 1].kohm;
            return r0 + (celsius - t0) * (r1 - r0) / (t1 - t0);
        }
    }
    return table[tableSize - 1].kohm;
}

float NTCLookup::kohmToTemperature(float kohm) {
    if (tableSize == 0) return 0.0f;

    if (kohm >= table[0].kohm) return table[0].tempC;
    if (kohm <= table[tableSize - 1].kohm) return table[tableSize - 1].tempC;

    for (int i = 0; i < tableSize - 1; i++) {
        float r0 = table[i].kohm;
        float r1 = table[i + 1].kohm;

        if (kohm <= r0 && kohm >= r1) {
            float t0 = table[i].tempC;
            float t1 = table[i + 1].tempC;
            return t0 + (kohm - r0) * (t1 - t0) / (r1 - r0);
        }
    }
    return table[tableSize - 1].tempC;
}